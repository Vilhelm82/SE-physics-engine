import sympy as sp, time
T0 = time.time(); CH = []
def check(t, ok, n=""):
    CH.append(bool(ok))
    print(f"  [{'PASS' if ok else 'FAIL'}][{time.time()-T0:5.1f}s] {t}" + (f" -- {n}" if n else ""), flush=True)
def z(e):
    e = sp.sympify(e)
    for f in (sp.simplify, lambda q: sp.simplify(sp.expand(q)), sp.cancel, sp.factor):
        try:
            if f(e) == 0: return True
        except Exception: pass
    return False

a, b, gam = sp.symbols('a b gamma', real=True)
z1, z2 = sp.symbols('z1 z2', real=True)
b0, r1, r2, ep = sp.symbols('b0 rho1 rho2 epsilon', positive=True)
w1, w2 = sp.symbols('w1 w2', positive=True)
sig = 1
eps = 1 - gam**2; W = a**2 + b**2 - 2*a*b*gam; delta = eps + W; F = eps/delta
cella = {a: sig*b + z1, gam: sig*(1 - z2)}          # z1 = a - sigma b, z2 = 1 - sigma gamma

print("=== c1: the seat's invariants in Cella coordinates ===")
eps_c, W_c, del_c = [sp.expand(e.subs(cella)) for e in (eps, W, delta)]
check("c1a eps = z2 (2 - z2)", z(eps_c - z2*(2 - z2)))
check("c1b W = z1^2 + 2 sigma a b z2  (with a = sigma b + z1)", z(W_c - (z1**2 + 2*sig*(sig*b + z1)*b*z2)))
check("c1c delta = z1^2 + 2 (1 + sigma a b) z2 - z2^2", z(del_c - (z1**2 + 2*(1 + sig*(sig*b + z1)*b)*z2 - z2**2)))
del_lead = sp.expand(del_c.subs(b, b0))
check("c1d at the pinch: delta = z1^2 + 2(1 + b0^2) z2 + (2 b0 z1 z2 - z2^2): two LEADING monomials (2,0) and (0,1), the rest inward",
      z(sp.Poly(del_lead, z1, z2).coeff_monomial(z1**2) - 1) and z(sp.Poly(del_lead, z1, z2).coeff_monomial(z2) - 2*(1 + b0**2)))

print("=== c2: the Newton polygon's balanced face is weight (1,2) ===")
mons = sp.Poly(del_lead, z1, z2).monoms()
outer = [m for m in mons if not any((n[0] <= m[0] and n[1] <= m[1] and n != m) for n in mons)]
check("c2a the outer (Newton) vertices of delta are exactly {(2,0), (0,1)}", sorted(outer) == [(0, 1), (2, 0)])
wsol = sp.solve(sp.Eq(2*w1, w2), w2)
check("c2b the weight on which they balance: <w,(2,0)> = <w,(0,1)>  =>  w2 = 2 w1: the (1,2) blow-up of PINCH-2 is Thm 7.2's balanced face", wsol == [2*w1])
check("c2c eps's Newton vertex is (0,1) alone: eps has NO balanced face; the ratio-dependence comes entirely from the DENOMINATOR", sorted(sp.Poly(sp.expand(eps_c), z1, z2).monoms())[0] == (0, 1))

print("=== c3: Thm 7.2 on the balanced face -- the ratio-dependent front form (Consequence 7.8) ===")
path = {z1: r1*ep, z2: r2*ep**2}
F_bal = sp.limit((eps_c/del_lead).subs(path), ep, 0, '+')
check("c3a along z1 = rho1 eps, z2 = rho2 eps^2: F -> 2 rho2/(rho1^2 + 2(1+b0^2) rho2)", z(F_bal - 2*r2/(r1**2 + 2*(1 + b0**2)*r2)))
check("c3b it depends on the approach RATIO rho2/rho1^2 -- front-form data, not exponent data (7.8); rho1 = 1, rho2 = lam gives PINCH-2 q7b",
      F_bal.has(r1) and F_bal.has(r2) and z(F_bal.subs({r1: 1, r2: sp.Symbol('lam')}) - 2*sp.Symbol('lam')/(1 + 2*sp.Symbol('lam')*(1 + b0**2))))

print("=== c4: off the balanced face, exponents suffice ===")
F_tr = sp.limit((eps_c/del_lead).subs({z1: r1*ep, z2: r2*ep}), ep, 0, '+')          # w = (1,1): gamma leaves first
check("c4a weight (1,1) [gamma leaves at first order]: F -> 1/(1+b0^2), ratio-INDEPENDENT -- PINCH-1's transverse class", z(F_tr - 1/(1 + b0**2)) and not F_tr.has(r1))
