#   Will: Gamma_4 is a TWISTED intertwiner, Gamma_4 rho_+(x) = rho_-(alpha(x)) Gamma_4 with alpha the grade involution
#   (exact).  With Gamma_4 = [[0, a Gamma_C],[b Gamma_C, 0]] and Gamma_C^T = -Gamma_C:  Gamma_4^T = Gamma_4 iff b = -a
#   iff Gamma_4^2 = +a^2 (self-adjoint observable -> Cl(3,1));  Gamma_4^T = -Gamma_4 iff b = a iff Gamma_4^2 = -a^2
#   (skew-adjoint generator -> Cl(2,2)).  CAUTION: the transpose must be replaced by the adjoint induced by the seat's
#   actual spinor bilinear B, Gamma^dag = B^{-1} Gamma^T B, and B must be DERIVED from the readout, not chosen for 3+1.
#   Boundaries: the algebra gives two chiral sectors ('particle and shadow' is interpretation); measuring Gamma_4
#   selects superpositions of the I = +-1 blocks, not the blocks, since {I, Gamma_4} = 0.
# CHECKS:
#   b1  twisted-intertwiner relation, exact.
#   b2  plain transpose: symmetric <-> square +a^2; antisymmetric <-> square -a^2.
#   b3  the seat's per-block spinor bilinear: solve for B_2 invariant under the spin group of the seat's form
#       (generated by the three bivectors).  Result: unique up to scale, ANTISYMMETRIC (symplectic), B_2 = Gamma_C.
#   b4  on the 4-dim space the Cl(2,1)-invariant bilinear is B_4 = diag(b+ Gamma_C, b- Gamma_C): two scales, one
#       relative sign s = sgn(b+ b-).  Under the induced adjoint, Gamma_4 self-adjoint  <=>  Gamma_4^2 = s a^2.
#       THE SIGNATURE OF THE FOURTH DIRECTION IS THE RELATIVE SIGN OF THE SPINOR BILINEAR ACROSS THE SHEETS.
#   b5  does requiring B_4 to be Gamma_4-invariant (up to sign) fix s?  Computed.
#   b6  the measurement boundary: Gamma_4's eigenvectors have both block components nonzero; I and Gamma_4 have no
#       joint eigenvector; a definite block needs an I-measurement.
